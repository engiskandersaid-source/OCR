export type Dict = (typeof dict)["fr"];

const I18nCtx = createContext<{ locale: Locale; t: Dict; setLocale: (l: Locale) => void } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fr");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("locale");
      if (saved === "fr" || saved === "en") setLocaleState(saved);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = (l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem("locale", l);
    } catch {}
  };

  return <I18nCtx.Provider value={{ locale, t: dict[locale], setLocale }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}

export function formatAmount(amount: number, currency: string | null, locale: Locale) {
  const tag = locale === "fr" ? "fr-FR" : "en-US";
  try {
    if (currency) return new Intl.NumberFormat(tag, { style: "currency", currency }).format(amount);
  } catch {}
  return new Intl.NumberFormat(tag, { maximumFractionDigits: 3 }).format(amount) + (currency ? ` ${currency}` : "");
}

export function formatDate(iso: string, locale: Locale) {
  const d = new Date(`${iso}T00:00:00Z`);
  return new Intl.DateTimeFormat(locale === "fr" ? "fr-FR" : "en-GB", {
    day: "2-digit",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(d);
}
